export const LINE_H = 11;
const TOP = 2; // rows reserved for accents above capitals
const CELL_H = 11;

const glyphs = new Map(); // char -> {w, px: [[x,y]...]}

function fromRows(rows) {
  const w = Math.max(...rows.map((r) => r.length));
  const px = [];
  rows.forEach((r, y) => {
    for (let x = 0; x < r.length; x++) if (r[x] === '#') px.push([x, y + TOP]);
  });
  return { w, px };
}
for (const [ch, rows] of Object.entries(RAW)) glyphs.set(ch, fromRows(rows));
for (const [ch, [base, acc]] of Object.entries(COMPOSED)) {
  const g = glyphs.get(base);
  const upper = base === base.toUpperCase() && base !== 'ı';
  const marks = ACC[acc](g.w).map(([x, y]) => [x, y + (upper ? 0 : TOP)]);
  glyphs.set(ch, { w: g.w, px: [...g.px, ...marks] });
}
for (const [ch, [base, marks]] of Object.entries(BELOW)) {
  const g = glyphs.get(base);
  glyphs.set(ch, { w: g.w, px: [...g.px, ...marks.map(([x, y]) => [x, y + TOP])] });
}

function glyph(ch) {
  return glyphs.get(ch) || glyphs.get(ch.normalize('NFD')[0]) || glyphs.get('?');
}

export function charWidth(ch) {
  return glyph(ch).w;
}

export function textWidth(s) {
  let w = 0;
  for (const ch of s) w += glyph(ch).w + 1;
  return w ? w - 1 : 0;
}

// Atlas: all glyphs drawn once in white, then tinted per colour on demand.
let atlas = null;
const atlasPos = new Map();
const tinted = new Map();

function buildAtlas() {
  const chars = [...glyphs.keys()];
  const W = 512;
  let x = 0,
    y = 0;
  for (const ch of chars) {
    const g = glyphs.get(ch);
    if (x + g.w + 1 > W) {
      x = 0;
      y += CELL_H;
    }
    atlasPos.set(ch, [x, y]);
    x += g.w + 1;
  }
  atlas = document.createElement('canvas');
  atlas.width = W;
  atlas.height = y + CELL_H;
  const c = atlas.getContext('2d');
  c.fillStyle = '#fff';
  for (const ch of chars) {
    const [ax, ay] = atlasPos.get(ch);
    for (const [px, py] of glyphs.get(ch).px) c.fillRect(ax + px, ay + py, 1, 1);
  }
}

export function fontAtlas(color) {
  if (!atlas) buildAtlas();
  let t = tinted.get(color);
  if (!t) {
    t = document.createElement('canvas');
    t.width = atlas.width;
    t.height = atlas.height;
    const c = t.getContext('2d');
    c.drawImage(atlas, 0, 0);
    c.globalCompositeOperation = 'source-in';
    c.fillStyle = color;
    c.fillRect(0, 0, t.width, t.height);
    tinted.set(color, t);
  }
  return t;
}

/** Calls draw(atlasX, atlasY, w, h, dx, dy) for each glyph of s. */
export function layoutText(s, x, y, draw) {
  let cx = x;
  for (const ch of s) {
    const key = glyphs.has(ch) ? ch : glyphs.has(ch.normalize('NFD')[0]) ? ch.normalize('NFD')[0] : '?';
    const g = glyphs.get(key);
    const [ax, ay] = (atlas || (buildAtlas(), atlas)) && atlasPos.get(key);
    if (g.px.length) draw(ax, ay, g.w, CELL_H, cx, y);
    cx += g.w + 1;
  }
  return cx - x;
}

/** Word-wraps text to a pixel width. Honours '\n'. */
export function wrapText(s, maxW) {
  const out = [];
  for (const para of s.split('\n')) {
    const words = para.split(' ');
    let line = '';
    for (let w of words) {
      const test = line ? line + ' ' + w : w;
      if (textWidth(test) <= maxW) {
        line = test;
        continue;
      }
      if (line) out.push(line);
      // break very long words
      while (textWidth(w) > maxW) {
        let k = w.length;
        while (k > 1 && textWidth(w.slice(0, k)) > maxW) k--;
        out.push(w.slice(0, k));
        w = w.slice(k);
      }
      line = w;
    }
    out.push(line);
  }
  return out;
}
