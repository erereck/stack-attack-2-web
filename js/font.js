// Accent placement relative to a glyph of width w. Lowercase: rows 0-1, uppercase: rows -2..-1.
const ACC = {
  acute: (w) => {
    const x = Math.ceil(w / 2);
    return [[x, 0], [x - 1, 1]];
  },
  grave: (w) => {
    const x = Math.ceil(w / 2);
    return [[x - 1, 0], [x, 1]];
  },
  circ: (w) => (w % 2 ? [[(w - 1) / 2, 0], [(w - 1) / 2 - 1, 1], [(w - 1) / 2 + 1, 1]] : [[w / 2 - 1, 0], [w / 2, 0], [w / 2 - 2, 1], [w / 2 + 1, 1]]),
  tilde: (w) => {
    const o = Math.max(0, Math.floor((w - 4) / 2));
    return w < 4 ? [[0, 1], [1, 0], [2, 1]] : [[o, 1], [o + 1, 0], [o + 2, 1], [o + 3, 0]];
  },
  uml: (w) => (w >= 4 ? [[0, 1], [w - 1, 1]] : [[0, 1], [2, 1]]),
  dot: (w) => [[Math.floor((w - 1) / 2), 1]],
  ring: (w) => {
    const c = Math.floor((w - 1) / 2);
    return [[c, 0], [c + 1, 0], [c, 1], [c + 1, 1]];
  },
};
