/** microedition.locale -> language file, falling back to English like class c. */
export function detectLang() {
  const l = (navigator.languages && navigator.languages[0]) || navigator.language || 'en';
  if (/^pt-(PT|AO|MZ)/i.test(l)) return 'pt';
  if (/^pt/i.test(l)) return 'pt-BR';
  const base = l.slice(0, 2).toLowerCase();
  return GAME_LANGS[base] ? base : 'en';
}

